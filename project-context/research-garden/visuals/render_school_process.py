def font(n, bold=False):
    return ImageFont.truetype(BOLD if bold else REG, round(n*S))

def text(x, y, t, n=21, color=INK, bold=False):
    d.text((round(x*S), round(y*S)), t, font=font(n, bold), fill=color)

def wrap(t, width, n=21, bold=False):
    out=[]
    for para in t.split('\n'):
        line=''
        for word in para.split():
            test=(line+' '+word).strip()
            if d.textlength(test, font=font(n,bold)) > width*S and line:
                out.append(line);line=word
            else: line=test
        out.append(line)
    return out

def lines(x,y,t,width,n=21,color=INK,bold=False,lh=1.28):
    for line in wrap(t,width,n,bold):
        text(x,y,line,n,color,bold);y+=n*lh
    return y

def box(x,y,w,h,title,blocks,accent=BLUE,fill='#FFFFFF',body=21):
    d.rounded_rectangle((x*S,y*S,(x+w)*S,(y+h)*S),radius=18*S,fill=fill,
                        outline='#D5E0E9',width=2*S)
    d.rounded_rectangle((x*S,y*S,(x+7)*S,(y+h)*S),radius=3*S,fill=accent)
    cy=lines(x+30,y+25,title,w-60,27,accent,True)+18
    for t,bold in blocks:
        cy=lines(x+30,cy,t,w-60,body,INK,bold)+12
    if cy > y+h-12:
        raise ValueError(f'Overflow {title}: {cy-(y+h)}')

def arrow(points,color=LINE,dashed=False):
    pts=[(int(x*S),int(y*S)) for x,y in points]
    for a,b in zip(pts,pts[1:]):
        if dashed:
            length=math.dist(a,b); count=max(1,int(length/(14*S)))
            for i in range(count):
                t0=i/count;t1=min(1,t0+0.56/count)
                d.line([(a[0]+(b[0]-a[0])*t0,a[1]+(b[1]-a[1])*t0),
                        (a[0]+(b[0]-a[0])*t1,a[1]+(b[1]-a[1])*t1)],fill=color,width=3*S)
        else:d.line([a,b],fill=color,width=4*S)
    a,b=pts[-2:];ang=math.atan2(b[1]-a[1],b[0]-a[0]);r=13*S
    d.polygon([b,(b[0]-r*math.cos(ang-.48),b[1]-r*math.sin(ang-.48)),
                 (b[0]-r*math.cos(ang+.48),b[1]-r*math.sin(ang+.48))],fill=color)

